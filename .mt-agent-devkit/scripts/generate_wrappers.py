"""Regenerate compatibility/discovery wrappers from the shared inventory.

No canonical file is generated or overwritten. Use --check in CI.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
SKILL_SOURCE = re.compile(r"^\.(?:claude|antigravity|codex)/skills/([a-z0-9-]+)/SKILL\.md$")
SKILL_DESTINATION = re.compile(r"^\.mt-agent-devkit/skills/([a-z0-9-]+)/SKILL\.md$")


def skill_frontmatter(text: str) -> dict:
    """Parse the flat discovery frontmatter; raise ValueError when malformed."""
    match = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not match:
        raise ValueError("missing discovery frontmatter")
    fields = {}
    for line in match.group(1).splitlines():
        key, sep, value = line.partition(": ")
        if not sep or not value.strip():
            raise ValueError(f"malformed frontmatter line: {line!r}")
        fields[key] = value.strip()
    if set(fields) != {"name", "description"}:
        raise ValueError("frontmatter must hold exactly name and description")
    return fields


def render_skill(entry: dict, root: Path = ROOT) -> str:
    """Discovery wrapper: canonical frontmatter plus one pointer to the canonical file."""
    source, destination = entry["source"], entry["destination"]
    wrapper, canonical = SKILL_SOURCE.match(source), SKILL_DESTINATION.match(destination)
    if not wrapper or not canonical or wrapper.group(1) != canonical.group(1):
        raise ValueError(f"skill wrapper must point at its own canonical skill: {source}")
    fields = skill_frontmatter((root / destination).read_text(encoding="utf-8"))
    if fields["name"] != canonical.group(1):
        raise ValueError(f"skill name does not match its directory: {destination}")
    return (f"---\nname: {fields['name']}\ndescription: {fields['description']}\n---\n\n"
            f"Read `{destination}` in full before acting; it is the only owner of this skill's rules.\n")


def render(entry: dict) -> str:
    source, destination = entry["source"], entry["destination"]
    if entry.get("renderer") == "skill":
        return render_skill(entry)
    if source.endswith(".py"):
        return ('"""Generated compatibility wrapper; edit the canonical source instead."""\n'
                'from pathlib import Path\nimport runpy\n'
                f'runpy.run_path(str(Path(__file__).resolve().parents[4] / "{destination}"), run_name="__main__")\n')
    frontmatter = entry.get("discovery_frontmatter", "")
    title = Path(source).stem.replace("_", " ")
    text = frontmatter + f"# {title} — Generated Wrapper\n\n"
    text += f"<!-- Harness source: {destination} -->\n"
    text += "Generated by `.mt-agent-devkit/scripts/generate_wrappers.py`; do not edit.\n\n"
    if "Read_On_Demand" in source:
        text += (f"This file contains no rules. Read only the triggered numbered section from `{destination}`\n"
                 "with `python .mt-agent-devkit/scripts/read_section.py`; preserve the section\n"
                 "number in the citation. Do not load the complete on-demand file at startup.\n")
    else:
        text += (f"Before acting, load `{destination}` and follow its read routing. Reading this\n"
                 "wrapper alone does not satisfy any mandatory-read gate.\n")
        if "Bootstrap" in source:
            text += "Read the canonical bootstrap in full. Every section is mandatory.\n"
    text += ("\nUse the already selected provider adapter and supplied runtime bindings.\n"
             "Never load another provider's adapter to satisfy a shared reference.\n")
    return text


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    inventory = json.loads((ROOT / ".mt-agent-devkit/contracts/migration-inventory.json").read_text())
    mismatches = []
    for entry in inventory["files"]:
        if entry["ownership"] != "generated-wrapper":
            continue
        path = ROOT / entry["source"]
        expected = render(entry)
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != expected:
                mismatches.append(entry["source"])
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8", newline="\n")
    for path in mismatches:
        print(f"[ERROR] {path}: generated wrapper drift")
    return int(bool(mismatches))


if __name__ == "__main__":
    raise SystemExit(main())
